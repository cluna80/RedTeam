# ---------------------------------------------------------------------------
# Process one finding
# ---------------------------------------------------------------------------

def process_finding(
    finding: FindingRecord,
    out_dir: Path,
    min_severity: Severity,
) -> tuple[Path | None, Path | None]:
    if _SEVERITY_RANK[finding.severity] < _SEVERITY_RANK[min_severity]:
        print(f"  skip {finding.finding_id[:8]} ({finding.severity.value}) — below threshold")
        return None, None

    reg_path    = generate_regression(finding, out_dir)
    sketch_path = generate_fix_sketch(finding, out_dir)

    print(f"  regression  → {reg_path}")
    print(f"  fix sketch  → {sketch_path}")
    print(f"  ⚠  HUMAN REVIEW REQUIRED — do not auto-merge")

    return reg_path, sketch_path


