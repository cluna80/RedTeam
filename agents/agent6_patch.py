def main() -> None:
    parser = argparse.ArgumentParser(
        description="QCB PatchProposer — generate regression tests + fix sketches (human gate)"
    )
    parser.add_argument("--finding",         type=Path, help="Single finding JSON file")
    parser.add_argument("--all-findings",    type=Path, help="Directory of finding JSON files")
    parser.add_argument("--regressions-dir", type=Path, default=Path("agents/regressions"))
    parser.add_argument(
        "--min-severity",
        default="high",
        choices=["critical", "high", "medium", "low", "info"],
        help="Only generate for findings at or above this severity (default: high)",
    )
    args = parser.parse_args()

    out = args.regressions_dir
    out.mkdir(parents=True, exist_ok=True)
    min_sev = Severity(args.min_severity)

    findings: list[FindingRecord] = []
    if args.finding:
        findings.append(FindingRecord.load(args.finding))
    elif args.all_findings:
        for p in sorted(args.all_findings.glob("*.json")):
            try:
                findings.append(FindingRecord.load(p))
            except Exception as exc:
                print(f"  WARN: could not load {p}: {exc}", file=sys.stderr)
    else:
        parser.error("Provide --finding or --all-findings")

    # Sort by severity descending
    findings.sort(key=lambda f: _SEVERITY_RANK[f.severity], reverse=True)

    print(f"[patch] Processing {len(findings)} finding(s) (min_severity={min_sev.value})…")
    generated = 0
    for f in findings:
        print(f"\n[patch] {f.finding_id[:8]} — {f.title} ({f.severity.value})")
        reg, sketch = process_finding(f, out, min_sev)
        if reg is not None:
            generated += 1

    print(f"\n[patch] Done. {generated} regression(s) generated in {out}/")
    print("[patch] NO auto-merge. A human must review, adjust, and merge each file.")


if __name__ == "__main__":
    main()
