def _steps_as_comments(steps: list[str]) -> str:
    return "\n".join(f"    # {s}" for s in steps)


def _evidence_repr(evidence: dict) -> str:
    """Format evidence as a compact inline comment, max 120 chars per line."""
    raw = json.dumps(evidence, indent=None)
    if len(raw) < 200:
        return raw
    return raw[:197] + "…"


