def _rejected(r: httpx.Response) -> bool:
    """Return True if the response is a proper protocol rejection."""
    if r.status_code in (400, 401, 403, 409, 422):
        return True
    try:
        body = r.json()
        code = body.get("check_tx", {{}}).get("code") or body.get("code")
        return code not in (None, 0)
    except Exception:
        return False


