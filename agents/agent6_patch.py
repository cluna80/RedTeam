    # Build evidence as a Python dict literal for use in the test body
    evidence_json = json.dumps(finding.evidence, indent=8)

    # Build the steps block: each step becomes an inline comment above the code
    steps_block = _steps_as_comments(finding.steps)

    # Determine the primary URL/endpoint from evidence (best-effort)
